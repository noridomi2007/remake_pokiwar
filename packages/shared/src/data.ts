function defaultPassiveForTier(pet: PetDef): PetDef['passiveSkill'] {
  if (pet.passiveSkill) return pet.passiveSkill;
  if (pet.tier === 'MEGA') {
    return {
      name: 'Chiến Ý Mega',
      description: 'Mất mỗi 10% HP tăng +5% sức Tấn Công (Cuồng Huyết).',
      kind: 'CUONG_HUYET',
      value: 0.05,
    };
  }
  if (pet.tier === 'GALAXY') {
    return {
      name: 'Tinh Vân Xuyên Phá',
      description: 'Xuyên 28% phòng thủ đối thủ trong trận đấu.',
      kind: 'XUYEN_GIAP',
      value: 0.28,
    };
  }
  if (pet.tier === 'ANCIENT' || pet.tier === 'MECH') {
    return {
      name: 'Bất Diệt Cổ Đại',
      description: 'Tự động Hồi Sinh 1 lần mỗi trận với 42% HP & Giáp!',
      kind: 'HOI_SINH',
      value: 1,
    };
  }
  return undefined;
}

